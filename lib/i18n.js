export const RTL_LANGS = ['ar', 'he', 'ur', 'fa'];

export function langMeta(code) {
  return LANGS.find((l) => l.code === code) || LANGS[0];
}
export function isRTL(code) {
  return RTL_LANGS.includes(code) || langMeta(code).dir === 'rtl';
}

